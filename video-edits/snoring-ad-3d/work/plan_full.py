for i, c in enumerate(plan):
    if c["kind"] == "3d":
        name = f"c{i:03d}_{c['scene']}.mp4"
        jobs.append({"scene": c["scene"], "params": c["params"], "dur": round(c["e"] - c["s"] + 0.15, 2), "out": f"{S}/out3d/{name}", "skipIfExists": True})
